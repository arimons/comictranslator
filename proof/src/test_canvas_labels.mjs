import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const {placeCanvasLabels,promotedTgIds} = await import(`data:text/javascript;base64,${readFileSync('frontend/src/canvasLabels.js').toString('base64')}`);
const rect = {x:30,y:50,width:220,height:30};
const labels = Array.from({length:5},(_,i)=>({id:`R${i+1}`,kind:'region',rect:{...rect,y:50+i*12},width:90,inlineWidth:24,height:18}));
const overlaps = (a,b)=>Math.min(a.x+a.width,b.x+b.width)>Math.max(a.x,b.x) && Math.min(a.y+a.height,b.y+b.height)>Math.max(a.y,b.y);
const image = {x:20,y:0,width:270,height:400};
const gutter = placeCanvasLabels(labels,labels.map(l=>l.rect),image,{width:500,height:400});
assert.equal(gutter.length,5);
assert(gutter.every(l=>l.outside && l.x>=302 && l.x+l.width<=500));
assert(gutter.every((a,i)=>gutter.slice(i+1).every(b=>!overlaps(a,b))));
const inline = placeCanvasLabels([{...labels[0],rect}], [rect],{x:0,y:0,width:300,height:400},{width:300,height:400});
assert.equal(inline[0].outside,false);
assert.equal(inline[0].width,24);
assert(!overlaps(inline[0],rect));
const hidden = placeCanvasLabels([{...labels[0],rect:{...rect,x:600}}],[],image,{width:500,height:400});
assert.equal(hidden.length,0);
const ids = promotedTgIds([{anchor_ids:[3,'4',3,null]},{anchor_ids:[5]}]);
assert.deepEqual([...ids],[3,4,5]);
const dense = placeCanvasLabels(labels,labels.map(l=>l.rect),{x:0,y:0,width:300,height:400},{width:300,height:400});
assert(dense.every(l=>l.x>=0 && l.y>=0 && l.x+l.width<=300 && l.y+l.height<=400));
